#!/usr/bin/env python3
"""Write the Google client secret into the program -- PRESS-0122 § 4.7.

    python3 scripts/write_google_secret.py [path]

Writes src/pressless/_google_secret.py (or <path>), which .gitignore names so
it is never committed. The value comes from the environment variable
GOOGLE_CLIENT_SECRET, as in a release job; where that is unset and this runs
in a terminal, it asks for it without showing what is typed.

Strips surrounding whitespace, then refuses, writing nothing, a value that is
empty or holds anything but ASCII letters, digits, '-' and '_'. Never prints
the value.
"""
from __future__ import annotations

import getpass
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from pressless import safe_write  # noqa: E402 -- after the path it is found on

DEFAULT = ROOT / "src" / "pressless" / "_google_secret.py"
_SHAPE = re.compile(r"[A-Za-z0-9_-]+")


def _asks() -> bool:
    """Whether someone is at a terminal to type the secret.

    On Windows `isatty` is also true of NUL, a character device like the
    console, and getpass then waits on the console for ever (it reads the
    console, not stdin). Only a real console input has a console mode;
    checked on the Windows box 2026-10-01.
    """
    if not sys.stdin.isatty():
        return False
    if sys.platform != "win32":
        return True
    import ctypes
    import msvcrt
    mode = ctypes.c_uint32()
    handle = msvcrt.get_osfhandle(sys.stdin.fileno())
    return bool(ctypes.windll.kernel32.GetConsoleMode(handle, ctypes.byref(mode)))


def from_environment_or_terminal(variable: str, prompt: str) -> str:
    """The environment variable, else what is typed at a terminal, else ''.

    Shared with write_usage_key.py. A value pasted into GitHub's secret box
    keeps a trailing line break, so surrounding whitespace is stripped.
    """
    value = os.environ.get(variable)
    if value is None:
        value = getpass.getpass(prompt) if _asks() else ""
    return value.strip()


def write_module(target: Path, text: str) -> None:
    """Write the module whole or not at all. A truncated one raises
    SyntaxError at import, which PRESS-0122 § 4.7's `except ImportError`
    does not catch, so the program would not start."""
    safe_write.write_whole(target, text, prefix=f".{target.name}.")


def main(argv: list[str]) -> int:
    target = Path(argv[0]) if argv else DEFAULT
    value = from_environment_or_terminal("GOOGLE_CLIENT_SECRET", "Google client secret: ")
    if not _SHAPE.fullmatch(value):
        print("No usable client secret: it must be non-empty and hold only letters, "
              "digits, '-' and '_'. Nothing was written.", file=sys.stderr)
        return 1
    write_module(target, "# Generated by scripts/write_google_secret.py -- never committed.\n"
                         f"CLIENT_SECRET = {value!r}\n")
    print(f"Wrote the client secret to {target}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
