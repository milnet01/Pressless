#!/usr/bin/env python3
"""Write the usage-report property's key into the program -- PRESS-0262 § 4.1.

    python3 scripts/write_usage_key.py [path]

Writes src/pressless/_usage_key.py (or <path>), which .gitignore names so it
is never committed. The two values come from the environment variables
PRESSLESS_USAGE_MEASUREMENT_ID and PRESSLESS_USAGE_API_SECRET, as in a
release job; where one is unset and this runs in a terminal, it asks for it
without showing what is typed.

Refuses, writing nothing, a measurement id that is not "G-" and capital
letters or digits, or a secret that is empty or holds anything but ASCII
letters, digits, '-' and '_'. Never prints either value.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from write_google_secret import _value  # noqa: E402 -- one reader for both scripts

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = ROOT / "src" / "pressless" / "_usage_key.py"
_ID = re.compile(r"G-[A-Z0-9]+")
_SECRET = re.compile(r"[A-Za-z0-9_-]+")


def main(argv: list[str]) -> int:
    target = Path(argv[0]) if argv else DEFAULT
    measurement_id = _value("PRESSLESS_USAGE_MEASUREMENT_ID", "Measurement id: ")
    if not _ID.fullmatch(measurement_id):
        print("No usable measurement id: it must be G- followed by capital letters and "
              "digits. Nothing was written.", file=sys.stderr)
        return 1
    secret = _value("PRESSLESS_USAGE_API_SECRET", "API secret: ")
    if not _SECRET.fullmatch(secret):
        print("No usable API secret: it must be non-empty and hold only letters, digits, "
              "'-' and '_'. Nothing was written.", file=sys.stderr)
        return 1
    target.write_text("# Generated by scripts/write_usage_key.py -- never committed.\n"
                      f"MEASUREMENT_ID = {measurement_id!r}\n"
                      f"API_SECRET = {secret!r}\n", encoding="utf-8")
    print(f"Wrote the usage-report key to {target}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
